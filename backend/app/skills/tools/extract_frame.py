"""Free, replay-safe extraction of a Run-owned video frame."""
from hashlib import sha256
from typing import Literal

from flask import current_app
from PIL import Image
from pydantic import BaseModel, ConfigDict, Field

from app.agent.search.scope import require_run
from app.api import AppError
from app.extensions import db
from app.models import Artifact, ToolInvocation
from app.services.artifact_service import ArtifactService
from app.services.job_service import JobService
from app.services.storage_service import StorageService
from app.services.video_media_service import VideoMediaService
from app.skills import job_backed
from app.skills.permissions import PRODUCTION, SYSTEM, WRITE
from app.skills.spec import ToolContext, ToolSpec
from app.utils.time_utils import utc_now

MOCK_VIDEO_BYTES = b"Mock video bytes generated by MockAdapter.\n"


class ExtractFrameInput(BaseModel):
    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)
    video_artifact_id: str = Field(min_length=1, max_length=80)
    position: Literal["first", "last"] = "last"
    timestamp_sec: float | None = Field(default=None, ge=0, strict=True)


class ExtractFrameOutput(BaseModel):
    artifact_id: str
    source_artifact_id: str
    position: Literal["first", "last"]
    timestamp_sec: float
    preview_url: str
    job_id: str


def validate_source(data, ctx):
    owner = require_run(ctx)
    source = job_backed.resolve_artifact(data.video_artifact_id, ctx=ctx)
    if not str(source.mime_type or "").startswith("video/"):
        raise AppError("INVALID_INPUT", "extract_frame requires a video artifact", 422)
    return owner, source


def run(data: ExtractFrameInput, ctx: ToolContext):
    owner, source = validate_source(data, ctx)
    invocation = ToolInvocation.query.filter_by(invocation_id=ctx.invocation_id, budget_scope=owner.run_id).one()
    existing = Artifact.query.filter(Artifact.meta["frame_extraction"]["invocation_id"].as_string() == ctx.invocation_id).first()
    if existing and StorageService.resolve(existing.file_path).is_file():
        return _finish(existing, invocation)
    directory = StorageService.root() / "agent" / "frames" / sha256(owner.run_id.encode()).hexdigest()
    directory.mkdir(parents=True, exist_ok=True)
    target = StorageService.resolve(existing.file_path) if existing else directory / (ctx.invocation_id + ".png")
    if not target.resolve().is_relative_to(StorageService.root()):
        raise AppError("INVALID_REFERENCE", "Extracted frame path is outside managed storage", 422)
    source_path = StorageService.resolve(source.file_path)
    if (current_app.config.get("MODEL_ADAPTER_MODE") == "mock" and source_path.stat().st_size == len(MOCK_VIDEO_BYTES)
            and source_path.read_bytes() == MOCK_VIDEO_BYTES):
        Image.new("RGB", (256, 256), (36, 54, 78)).save(target, format="PNG")
        timestamp = data.timestamp_sec or 0.0
    else:
        timestamp = VideoMediaService.extract_frame(source_path, target, position=data.position,
                                                    timestamp_sec=data.timestamp_sec)
    with Image.open(target) as image:
        image.verify()
    if existing:
        return _finish(existing, invocation)
    template = job_backed.ensure_agent_template()
    marker = {"run_id": owner.run_id, "target_type": "tail_frame"}
    if ctx.shot_task_id is not None:
        from app.agent.production_policy import job_marker
        marker = job_marker(ctx)
    job = JobService.create_job({"template_id": template.template_id, "strategy": "skill:extract_frame",
        **job_backed.node_selection([]), "job_config": {"agent_story_production": marker,
            "skill": {"tool_name": "extract_frame", "budget_scope": owner.run_id,
                      "invocation_id": ctx.invocation_id, "caller_role": ctx.role}}}, commit=False)
    artifact = ArtifactService.register_artifact(job, str(target), "tail_frame_image", metadata={
        "frame_extraction": {"invocation_id": ctx.invocation_id, "source_artifact_id": source.artifact_id,
                             "position": data.position, "timestamp_sec": timestamp}})
    job.status = "success"
    invocation.job = job
    return _finish(artifact, invocation)


def _finish(artifact, invocation):
    metadata = artifact.meta["frame_extraction"]
    output = {"artifact_id": artifact.artifact_id, "source_artifact_id": metadata["source_artifact_id"],
              "position": metadata["position"], "timestamp_sec": metadata["timestamp_sec"],
              "preview_url": f"/api/artifacts/{artifact.artifact_id}/preview", "job_id": artifact.job.job_id}
    invocation.job = artifact.job
    invocation.output_payload, invocation.status, invocation.finished_at = output, "success", utc_now()
    db.session.commit()
    return output


SPEC = ToolSpec(name="extract_frame", description="Extract a first, last or timestamped frame from a Run video locally; no model cost.",
    input_model=ExtractFrameInput, output_model=ExtractFrameOutput, handler=run, permission=WRITE,
    allowed_roles=frozenset({PRODUCTION, SYSTEM}), timeout_sec=240, max_retries=1)
