"""Bounded local video probing and complete decode checks; never opens URLs."""

from hashlib import sha256
import math
import re
import subprocess
from pathlib import Path

from flask import current_app

from app.api import AppError
from app.services.storage_service import StorageService
from app.services.video_compression_service import VideoCompressionService

MOCK_VIDEO_BYTES = b"Mock video bytes generated by MockAdapter.\n"


class MediaProbeService:
    @staticmethod
    def _path(path):
        source = Path(path).resolve()
        if not source.is_relative_to(StorageService.root()) or not source.is_file():
            raise AppError("MEDIA_MISSING", "Media file is missing or outside managed storage", 422)
        if source.stat().st_size <= 0:
            raise AppError("MEDIA_EMPTY", "Media file is empty", 422)
        return source

    @staticmethod
    def _run(path, *, audio=False, decode=False):
        try:
            binary = VideoCompressionService.resolve_ffmpeg()
        except FileNotFoundError as error:
            raise AppError("MEDIA_TOOL_UNAVAILABLE", "FFmpeg is required for media validation", 503) from error
        command = [binary, "-nostdin", "-hide_banner", "-xerror", "-err_detect", "explode",
            "-protocol_whitelist", "file,pipe", "-format_whitelist", "mov,matroska,webm",
            "-i", str(path), "-map", "0:a:0" if audio else "0:v:0"]
        command += ["-vn"] if audio else ["-an", "-fps_mode", "passthrough"]
        if not decode:
            command += ["-frames:a" if audio else "-frames:v", "1"]
        command += ["-progress", "pipe:1", "-nostats", "-f", "null", "-"]
        try:
            result = subprocess.run(command, capture_output=True, text=True, encoding="utf-8",
                errors="replace", timeout=300 if decode else 60)
        except subprocess.TimeoutExpired as error:
            raise AppError("MEDIA_TIMEOUT", "Local media validation exceeded its time limit", 422) from error
        if result.returncode:
            raise AppError("MEDIA_UNDECODABLE", "Media stream cannot be fully decoded", 422)
        return result.stderr, result.stdout

    @staticmethod
    def _metadata(stderr):
        header = stderr.split("Stream mapping:", 1)[0]
        video_lines = [line for line in header.splitlines() if re.search(r"Stream #\d+:\d+.*?Video:", line)]
        audio_lines = [line for line in header.splitlines() if re.search(r"Stream #\d+:\d+.*?Audio:", line)]
        if not video_lines:
            raise AppError("MEDIA_UNDECODABLE", "A video stream is required", 422)
        line = video_lines[0]
        duration = re.search(r"Duration:\s*(\d+):(\d+):(\d+(?:\.\d+)?)", header)
        size = re.search(r",\s*(\d+)x(\d+)(?=[\s,])", line)
        if not duration or not size:
            raise AppError("MEDIA_UNDECODABLE", "Finite duration and video dimensions are required", 422)
        seconds = int(duration[1]) * 3600 + int(duration[2]) * 60 + float(duration[3])
        fps = re.search(r",\s*(\d+(?:\.\d+)?)\s+fps(?:[\s,]|$)", line)
        codec = re.search(r"Video:\s*([^\s,(]+)(?:\s+\(([^)]+)\))?", line)
        pixel = re.search(r",\s*([a-z][a-z0-9]*)(?:\([^)]*\))?,\s*\d+x\d+", line)
        sar = re.search(r"\bSAR\s+(\d+:\d+)", line)
        tbn = re.search(r",\s*([\d.]+[kM]?)\s+tbn(?:[\s,]|$)", line)
        audio = None
        if audio_lines:
            audio_line = audio_lines[0]
            acodec = re.search(r"Audio:\s*([^\s,(]+)(?:\s+\(([^)]+)\))?", audio_line)
            rate = re.search(r",\s*(\d+)\s+Hz,\s*([^,]+)", audio_line)
            layout = rate[2].strip() if rate else None
            channels = {"mono": 1, "stereo": 2, "5.1": 6, "5.1(side)": 6, "7.1": 8}.get(layout)
            numeric = re.fullmatch(r"(\d+) channels?", layout or "")
            if numeric:
                channels = int(numeric[1])
            audio = {"codec": acodec[1] if acodec else None, "profile": acodec[2] if acodec else None,
                     "sample_rate": int(rate[1]) if rate else None,
                     "channels": channels, "channel_layout": layout}
        video = {"codec": codec[1] if codec else None, "profile": codec[2] if codec else None,
                 "pixel_format": pixel[1] if pixel else None, "time_base": tbn[1] if tbn else None,
                 "sar": sar[1] if sar else None, "level": None}
        complete = all(video[key] for key in ("codec", "profile", "pixel_format", "time_base", "sar"))
        complete = bool(complete and fps and (audio is None or (all(audio.values())
            and audio["codec"] == "aac" and audio["profile"] == "LC")))
        streams = len(re.findall(r"Stream #\d+:\d+", header))
        return {"duration_sec": seconds, "width": int(size[1]), "height": int(size[2]),
            "fps": float(fps[1]) if fps else None, "video": video, "audio": audio,
            "has_audio": audio is not None, "stream_count": streams,
            "copy_compatible_metadata": complete and len(video_lines) == 1 and len(audio_lines) <= 1,
            "decoded": False, "mock": False, "duration_source": "container", "video_duration_verified": False}

    @staticmethod
    def _codec_parameters(path, codec):
        if codec != "h264":
            return None
        try:
            result = subprocess.run([VideoCompressionService.resolve_ffmpeg(), "-nostdin", "-hide_banner",
                "-v", "error", "-protocol_whitelist", "file,pipe", "-format_whitelist", "mov,matroska,webm",
                "-i", str(path), "-map", "0:v:0", "-frames:v", "1", "-an", "-c:v", "copy",
                "-bsf:v", "h264_mp4toannexb", "-f", "h264", "pipe:1"], capture_output=True, timeout=60)
            if result.returncode:
                return None
            units = [unit for unit in re.split(b"\x00\x00(?:\x00)?\x01", result.stdout)
                     if unit and unit[0] & 31 in {7, 8}]
            if {unit[0] & 31 for unit in units} != {7, 8}:
                return None
            return sha256(b"".join(len(unit).to_bytes(4, "big") + unit for unit in units)).hexdigest()
        except (OSError, subprocess.TimeoutExpired):
            return None

    @classmethod
    def probe(cls, path, *, decode=False, mock_duration_sec=None):
        source = cls._path(path)
        if (current_app.config.get("MODEL_ADAPTER_MODE") == "mock"
                and source.stat().st_size == len(MOCK_VIDEO_BYTES) and source.read_bytes() == MOCK_VIDEO_BYTES):
            if (not isinstance(mock_duration_sec, (int, float)) or isinstance(mock_duration_sec, bool)
                    or not math.isfinite(mock_duration_sec) or mock_duration_sec <= 0):
                raise AppError("MEDIA_UNDECODABLE", "Mock media requires its approved demonstration duration", 422)
            return {"duration_sec": float(mock_duration_sec), "container_duration_sec": float(mock_duration_sec), "width": 256, "height": 144, "fps": 25.0,
                "video": {"codec": "mock", "profile": None, "pixel_format": "yuv420p", "time_base": None,
                          "sar": "1:1", "level": None}, "audio": None, "has_audio": False, "stream_count": 1,
                "copy_compatible_metadata": False, "decoded": False, "mock": True,
                "duration_source": "mock_approved_plan", "video_duration_verified": False}
        stderr, progress = cls._run(source, decode=decode)
        result = cls._metadata(stderr)
        result["container_duration_sec"] = result["duration_sec"]
        signature = cls._codec_parameters(source, result["video"]["codec"])
        result["video"]["codec_parameters_hash"] = signature
        result["copy_compatible_metadata"] = bool(result["copy_compatible_metadata"] and signature)
        if decode:
            times = [int(value) for value in re.findall(r"^out_time_us=(\d+)$", progress, re.MULTILINE)]
            frames = [int(value) for value in re.findall(r"^frame=(\d+)$", progress, re.MULTILINE)]
            if not times or not frames or max(frames) <= 0 or "progress=end" not in progress:
                raise AppError("MEDIA_UNDECODABLE", "Video produced no complete decoded frames", 422)
            result["duration_sec"] = max(times) / 1_000_000
            result.update(decoded=True, duration_source="decoded_video", video_duration_verified=True)
            if result["has_audio"]:
                cls._run(source, audio=True, decode=True)
        if (not math.isfinite(result["duration_sec"]) or result["duration_sec"] <= 0
                or result["width"] <= 0 or result["height"] <= 0):
            raise AppError("MEDIA_UNDECODABLE", "Video has no usable duration or dimensions", 422)
        return result
